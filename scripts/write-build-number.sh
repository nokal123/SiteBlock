#!/bin/bash
# Writes Sources/SiteBlockCore/BuildNumber.swift, the one file that holds this build's number. The number is the count of
# commits on the checked-out branch, so it goes up with every commit and is the same on every machine for the same commit.
# The version everyone sees is 1.0.<this number>. When git is missing or this folder is not a git checkout, the number is 0.
# scripts/build.sh, scripts/test.sh and scripts/package.sh run this before they build. The file is generated and ignored by git.
#
#   scripts/write-build-number.sh
set -euo pipefail

# Work from the repository root, wherever the script is started from.
cd "$(dirname "$0")/.."

FILE="Sources/SiteBlockCore/BuildNumber.swift"

# Count the commits. Any failure (no git, not a checkout, no commits yet) or a non-numeric answer falls back to 0.
BUILD=0
if command -v git >/dev/null 2>&1; then
    COUNT="$(git rev-list --count HEAD 2>/dev/null || true)"
    if [[ "$COUNT" =~ ^[0-9]+$ ]]; then
        BUILD="$COUNT"
    fi
fi

CONTENT="// Generated by scripts/write-build-number.sh. Do not edit and do not commit: git ignores this file.
/// The number of commits this build was made from (0 when it was built without git). The version is 1.0 followed by this number.
public let siteBlockBuildNumber = $BUILD"

# Only rewrite the file when its text changes, so an unchanged number does not make Swift rebuild everything.
if [[ -f "$FILE" && "$(cat "$FILE")" == "$CONTENT" ]]; then
    exit 0
fi
printf '%s\n' "$CONTENT" > "$FILE"
echo "Build number: $BUILD"
